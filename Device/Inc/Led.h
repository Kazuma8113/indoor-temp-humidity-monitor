#ifndef __LED_H
#define __LED_H

#include <stdint.h>     /* uint32_t */

/* ============================================================================
 * 器件驱动：板载 LED（PC13，低电平点亮）
 *
 * 引脚写死在本文件内部 —— 这块板只有一个 LED。把它当参数暴露给上层，
 * 只会让 App 的业务代码里出现"引脚句柄"这种跟业务毫无关系的东西。
 *
 * 这里只有"翻转 / 熄灭"两个电气动作；。
 * ========================================================================== */

/* 初始化（上电熄灭）。由 App_Led_Init() 在创建状态机互斥锁时顺带调用。 */
void LED_Init(void);

/* 翻转一次电平，然后延时 Time 毫秒（让出 CPU） */
void LED_Flip(uint32_t Time);

/* 熄灭 */
void LED_Off(void);

#endif //__LED_H
