#ifndef BSP_WARM_H
#define BSP_WARM_H

/* ============================================================================
 * 板级封装：加热片（PD10）
 *
 * 低电平有效：On = 输出低，Off = 输出高。
 * ========================================================================== */

void Bsp_Warm_Init(void);     /* 初始化为关闭（输出高） */
void Bsp_Warm_On(void);       /* 内部拉低 */
void Bsp_Warm_Off(void);      /* 内部拉高 */

#endif /* BSP_WARM_H */
